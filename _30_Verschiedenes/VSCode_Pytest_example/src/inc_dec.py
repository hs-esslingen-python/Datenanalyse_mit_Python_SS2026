
# Das ist eine Beispiel-Datei für die VSCode-Pytest-Integration. Sie enthält einfache Funktionen zum Inkrementieren und Dekrementieren von Zahlen.

def increment(x):
    """
    Inkrementiere eine Zahl x um 1.
    Args:
        x (int or float): Die Zahl, die inkrementiert werden soll.
    Returns:
        int or float: Die inkrementierte Zahl.
    """
    return x + 1


def decrement(x):
    """
    Dekrementiere eine Zahl x um 1.
    Args:
        x (int or float): Die Zahl, die dekrementiert werden soll.
    Returns:
        int or float: Die dekrementierte Zahl.
    """
    return x - 1
